"""License inventory of every dataset asset, as a Markdown table in ``datasets/README.md``.

The table is generated from the manifests (``benchmarks/*/manifest.yaml`` and
``datasets/manifests/*.{yaml,jsonl}``) and sits between two HTML comment markers, so the
rest of the README is hand-written.
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Any

from geoevals.validation.validate import load_dataset_manifest, load_yaml

DEFAULT_README = Path("datasets/README.md")
"""Relative to the repository root."""

START_MARKER = "<!-- inventory:start (generated by `geoevals data inventory`; do not edit) -->"
END_MARKER = "<!-- inventory:end -->"

COLUMNS = (
    "Dataset",
    "Asset",
    "License",
    "Attribution",
    "Redistributable",
    "Used by",
    "Manifest",
)


class InventoryError(ValueError):
    """The README has no inventory markers, or they are out of order."""


@dataclass(frozen=True)
class InventoryRow:
    dataset_id: str
    asset_id: str
    license: str
    attribution: str
    redistributable: bool
    used_by: tuple[str, ...]
    manifest: str


def manifest_paths(root: Path) -> list[Path]:
    """Every shipped dataset manifest under ``root`` (the same set CI validates)."""
    paths = list((root / "benchmarks").glob("*/manifest.yaml"))
    for pattern in ("*.yaml", "*.jsonl"):
        paths += (root / "datasets" / "manifests").glob(pattern)
    return sorted(paths, key=lambda path: path.relative_to(root).as_posix())


def _benchmark_id(spec: Path) -> str | None:
    if not spec.is_file():
        return None
    document: Any = load_yaml(spec)
    return document.get("id") if isinstance(document, dict) else None


def _users(manifest: Path, root: Path) -> list[str]:
    """Where the manifest is used: every YAML file in a benchmark directory whose
    ``dataset_manifest`` points at it (the benchmark spec, or a pilot build's settings)."""
    users: list[str] = []
    for path in sorted((root / "benchmarks").glob("*/*.yaml")):
        document: Any = load_yaml(path)
        if not isinstance(document, dict) or "dataset_manifest" not in document:
            continue
        if (path.parent / document["dataset_manifest"]).resolve() != manifest.resolve():
            continue
        if path.name == "benchmark.yaml":
            users.append(f"benchmark `{document.get('id')}`")
            continue
        label = f"`{document.get('id', path.stem)}`"
        benchmark_id = _benchmark_id(path.parent / "benchmark.yaml")
        if benchmark_id:
            label += f" ({path.name} of benchmark `{benchmark_id}`)"
        users.append(label)
    return users


def inventory_rows(root: Path) -> list[InventoryRow]:
    """One row per asset of every manifest. Raises ``SpecValidationError`` on an invalid one."""
    rows: list[InventoryRow] = []
    for path in manifest_paths(root):
        manifest = load_dataset_manifest(path, check_git=False)
        users = tuple(_users(path, root))
        for asset in manifest.assets:
            rows.append(
                InventoryRow(
                    dataset_id=manifest.dataset_id,
                    asset_id=asset.asset_id,
                    license=asset.license,
                    attribution=asset.attribution,
                    redistributable=asset.redistributable,
                    used_by=users,
                    manifest=path.relative_to(root).as_posix(),
                )
            )
    return rows


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_table(rows: list[InventoryRow]) -> str:
    lines = [
        "| " + " | ".join(COLUMNS) + " |",
        "|" + "|".join(" --- " for _ in COLUMNS) + "|",
    ]
    for row in rows:
        cells = [
            f"`{row.dataset_id}`",
            f"`{row.asset_id}`",
            f"`{row.license}`",
            _cell(row.attribution),
            "yes" if row.redistributable else "**no**",
            _cell(", ".join(row.used_by)) if row.used_by else "not used",
            f"[`{row.manifest}`](../{row.manifest})",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def replace_table(readme_text: str, table: str) -> str:
    """The README text with the part between the markers replaced by ``table``."""
    start = readme_text.find(START_MARKER)
    end = readme_text.find(END_MARKER)
    if start < 0 or end < 0 or end < start:
        raise InventoryError(f"expected the markers {START_MARKER!r} and {END_MARKER!r}, in order")
    before = readme_text[: start + len(START_MARKER)]
    return f"{before}\n{table}{readme_text[end:]}"


def update_inventory(root: Path, readme: Path, write: bool) -> bool:
    """Regenerate the table; return True if the README was out of date (written if ``write``)."""
    current = readme.read_text(encoding="utf-8")
    updated = replace_table(current, render_table(inventory_rows(root)))
    if updated == current:
        return False
    if write:
        readme.write_text(updated, encoding="utf-8")
    return True
