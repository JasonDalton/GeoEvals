"""Licenses of the installed runtime dependencies of ``geoevals``, as a Markdown report.

The runtime dependencies are the ``Requires-Dist`` closure of the installed ``geoevals``
distribution with all of its extras, with environment markers evaluated for the running
interpreter. Development tools (pytest, ruff, pyright) are not in it. GeoEvals is MIT
licensed, so a GPL or AGPL runtime dependency is a release blocker; LGPL is not.
"""

import importlib.metadata as metadata
import re
from dataclasses import dataclass
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

DEFAULT_REPORT = Path("docs/dependency-licenses.md")
"""Relative to the repository root."""

ROOT_DISTRIBUTION = "geoevals"

_COPYLEFT = re.compile(
    r"\bA?GPL(?![\w])|GNU (Affero )?General Public License",
    re.IGNORECASE,
)
_CLASSIFIER_PREFIX = "License :: "
_OSI_PREFIX = "OSI Approved :: "
_MAX_LICENSE_FIELD = 80
"""A longer ``License`` field is usually the whole license text; use the classifiers instead."""


@dataclass(frozen=True)
class DependencyLicense:
    name: str
    version: str
    license: str
    """SPDX expression, short ``License`` field and/or trove classifiers; ``UNKNOWN`` if none."""

    @property
    def copyleft(self) -> bool:
        """True for a GPL or AGPL license. Alternatives of an SPDX ``OR`` count only if every
        one of them is copyleft (the user may pick the permissive one)."""
        alternatives = re.split(r"\s+OR\s+", self.license)
        return all(_COPYLEFT.search(part) for part in alternatives)


def _header(meta: metadata.PackageMetadata, name: str) -> str:
    """The first value of a metadata header, or "" (``meta[name]`` may raise on a missing one)."""
    values = meta.get_all(name) or []
    return str(values[0]).strip() if values else ""


def license_of(dist: metadata.Distribution) -> str:
    meta = dist.metadata
    expression = _header(meta, "License-Expression")
    if expression:
        return expression
    parts: list[str] = []
    field = _header(meta, "License")
    if field and "\n" not in field and len(field) <= _MAX_LICENSE_FIELD:
        parts.append(field)
    for classifier in meta.get_all("Classifier") or []:
        if classifier.startswith(_CLASSIFIER_PREFIX):
            name = classifier.removeprefix(_CLASSIFIER_PREFIX).removeprefix(_OSI_PREFIX)
            if name not in parts:
                parts.append(name)
    return "; ".join(parts) or "UNKNOWN"


def _requirements(dist: metadata.Distribution, extras: set[str]) -> list[Requirement]:
    selected: list[Requirement] = []
    for line in dist.requires or []:
        requirement = Requirement(line)
        marker = requirement.marker
        if marker is None or any(marker.evaluate({"extra": extra}) for extra in extras | {""}):
            selected.append(requirement)
    return selected


def runtime_dependencies(root: str = ROOT_DISTRIBUTION) -> list[DependencyLicense]:
    """The installed runtime dependency closure of ``root`` (all extras), sorted by name.

    Raises ``PackageNotFoundError`` if a required distribution is not installed.
    """
    root_dist = metadata.distribution(root)
    extras = set(root_dist.metadata.get_all("Provides-Extra") or [])
    seen: dict[str, metadata.Distribution] = {}
    pending: list[tuple[metadata.Distribution, set[str]]] = [(root_dist, extras)]
    visited: set[tuple[str, frozenset[str]]] = set()
    while pending:
        dist, dist_extras = pending.pop()
        key = (canonicalize_name(dist.metadata["Name"]), frozenset(dist_extras))
        if key in visited:
            continue
        visited.add(key)
        for requirement in _requirements(dist, dist_extras):
            child = metadata.distribution(requirement.name)
            seen[canonicalize_name(requirement.name)] = child
            pending.append((child, set(requirement.extras)))
    seen.pop(canonicalize_name(root), None)
    return [
        DependencyLicense(dist.metadata["Name"], dist.version, license_of(dist))
        for _, dist in sorted(seen.items())
    ]


def render_report(dependencies: list[DependencyLicense]) -> str:
    lines = [
        "# Dependency licenses",
        "",
        "Generated by `geoevals data licenses` (CI regenerates it on every run and fails on a GPL",
        "or AGPL runtime dependency). Do not edit by hand.",
        "",
        "These are the installed runtime dependencies of `geoevals` with all extras: the",
        "`Requires-Dist` closure, not the development tools. Environment markers are evaluated",
        "for the Python version and platform that generated the file, so a few platform-only",
        "packages can differ elsewhere. The license is the package's SPDX `License-Expression`,",
        "or else its short `License` field and license classifiers.",
        "",
        "GeoEvals is MIT licensed. GPL and AGPL dependencies are not allowed at runtime; LGPL",
        "and the permissive licenses below are.",
        "",
        "| Package | Version | License |",
        "| --- | --- | --- |",
    ]
    for dep in dependencies:
        license_text = dep.license.replace("|", "\\|")
        lines.append(f"| `{dep.name}` | {dep.version} | {license_text} |")
    return "\n".join(lines) + "\n"
